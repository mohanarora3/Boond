const enAll = { ...en, ...enM18, ...enPost };
const hiAll = { ...hi, ...hiM18, ...hiPost };

type Strings = typeof enAll;
export type StringKey = keyof Strings;

const STRINGS: Record<Lang, Strings> = { en: enAll, hi: hiAll };

interface I18n {
  lang: Lang;
  setLang: (l: Lang) => void;
  t: (key: StringKey, vars?: Record<string, string | number>) => string;
}

const I18nContext = createContext<I18n | null>(null);

function initialLang(): Lang {
  try {
    const saved = localStorage.getItem("boond.lang");
    if (saved === "en" || saved === "hi") return saved;
  } catch {
    /* storage unavailable */
  }
  return navigator.language?.startsWith("hi") ? "hi" : "en";
}

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(initialLang);
  useEffect(() => {
    document.documentElement.lang = lang;
  }, [lang]);

  const setLang = useCallback((l: Lang) => {
    setLangState(l);
    document.documentElement.lang = l;
    try {
      localStorage.setItem("boond.lang", l);
    } catch {
      /* storage unavailable */
    }
  }, []);

  const value = useMemo<I18n>(
    () => ({
      lang,
      setLang,
      t: (key, vars) =>
        STRINGS[lang][key].replace(/\{(\w+)\}/g, (_, name: string) => String(vars?.[name] ?? `{${name}}`)),
    }),
    [lang, setLang],
  );

  return createElement(I18nContext.Provider, { value }, children);
}

/** Renders a translated string, turning **text** into <strong>text</strong>. */
export function Rich({ text }: { text: string }) {
  const parts = text.split(/\*\*(.+?)\*\*/g);
  return createElement(
    Fragment,
    null,
    ...parts.map((part, i) => (i % 2 === 1 ? createElement("strong", { key: i, className: "font-bold text-cta" }, part) : part)),
  );
}

export function useI18n(): I18n {
  const ctx = useContext(I18nContext);
  if (!ctx) throw new Error("useI18n must be used inside I18nProvider");
  return ctx;
}
